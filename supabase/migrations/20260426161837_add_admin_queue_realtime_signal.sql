create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to postgres, service_role;

-- Sanitized signal table for moderator workspaces. It intentionally does not
-- expose report IDs, queue names, metadata, or moderation content.
create table if not exists public.admin_queue_change_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('insert', 'update', 'delete')),
  changed_at timestamptz not null default now()
);

create index if not exists admin_queue_change_events_changed_at_idx
  on public.admin_queue_change_events (changed_at desc);

alter table public.admin_queue_change_events enable row level security;

drop policy if exists "admin queue change events are readable" on public.admin_queue_change_events;
create policy "admin queue change events are readable" on public.admin_queue_change_events
for select to anon, authenticated
using (true);

revoke all on public.admin_queue_change_events from public, anon, authenticated;
grant select on public.admin_queue_change_events to anon, authenticated;

create or replace function private.enqueue_admin_queue_change_event()
returns trigger
language plpgsql
security definer
set search_path = public, private, pg_temp
as $$
begin
  insert into public.admin_queue_change_events (event_type)
  values (lower(tg_op));

  delete from public.admin_queue_change_events
  where changed_at < now() - interval '7 days';

  return coalesce(new, old);
end;
$$;

revoke all on function private.enqueue_admin_queue_change_event() from public, anon, authenticated;

drop trigger if exists garbage_reports_admin_queue_change_event on public.garbage_reports;
create trigger garbage_reports_admin_queue_change_event
after insert or update or delete on public.garbage_reports
for each row execute function private.enqueue_admin_queue_change_event();

-- Realtime should publish only sanitized signal tables to browsers.
do $$
begin
  if exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'garbage_reports'
  ) then
    alter publication supabase_realtime drop table public.garbage_reports;
  end if;

  if exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'report_upvotes'
  ) then
    alter publication supabase_realtime drop table public.report_upvotes;
  end if;

  if exists (
    select 1
    from information_schema.tables
    where table_schema = 'public'
      and table_name = 'public_report_change_events'
  ) and not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'public_report_change_events'
  ) then
    alter publication supabase_realtime add table public.public_report_change_events;
  end if;

  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'admin_queue_change_events'
  ) then
    alter publication supabase_realtime add table public.admin_queue_change_events;
  end if;
end $$;
