create schema if not exists extensions;
create extension if not exists postgis with schema extensions;
grant usage on schema extensions to anon, authenticated, service_role;

create table if not exists public.wards (
  ward_number integer primary key,
  ward_name text not null,
  zone text,
  assembly_constituency text not null,
  parliamentary_constituency text not null,
  center_lat numeric(10, 7) not null,
  center_lng numeric(10, 7) not null,
  locality_name text,
  boundary_geojson jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.representatives (
  id integer generated by default as identity primary key,
  name text not null,
  role text not null check (role in ('mla', 'mp')),
  party text not null,
  constituency text not null,
  phone text,
  email text,
  photo_url text,
  twitter_handle text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (role, constituency)
);

create table if not exists public.garbage_reports (
  id uuid primary key default gen_random_uuid(),
  latitude numeric(10, 7) not null,
  longitude numeric(10, 7) not null,
  gps_latitude numeric(10, 7),
  gps_longitude numeric(10, 7),
  gps_accuracy_meters numeric(10, 2),
  gps_recorded_at timestamptz,
  location_source text not null default 'ward_center' check (
    location_source in ('gps', 'ward_center')
    and (
      location_source = 'ward_center'
      or (gps_latitude is not null and gps_longitude is not null)
    )
  ),
  ward_number integer not null references public.wards(ward_number),
  address text not null,
  severity text not null default 'medium' check (severity in ('small', 'medium', 'large', 'massive')),
  category text not null default 'mixed' check (category in ('household', 'construction', 'mixed', 'e-waste', 'biomedical')),
  status text not null default 'unresolved' check (status in ('unresolved', 'resolved')),
  photo_url text,
  reporter_id uuid,
  reporter_name text,
  upvote_count integer not null default 1,
  resolved_at timestamptz,
  resolved_photo_url text,
  resolved_by_name text,
  resolved_lat numeric(10, 7),
  resolved_lng numeric(10, 7),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  is_test boolean not null default false,
  moderation_status text not null default 'flagged' check (moderation_status in ('flagged', 'approved', 'rejected')),
  moderation_metadata jsonb not null default '{}'::jsonb,
  flag_count integer not null default 0,
  constraint garbage_reports_latitude_bounds_check check (latitude between -90 and 90),
  constraint garbage_reports_longitude_bounds_check check (longitude between -180 and 180),
  constraint garbage_reports_gps_bounds_check check (
    (gps_latitude is null or gps_latitude between -90 and 90)
    and (gps_longitude is null or gps_longitude between -180 and 180)
    and (gps_accuracy_meters is null or gps_accuracy_meters >= 0)
  )
);

create table if not exists public.report_upvotes (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.garbage_reports(id) on delete cascade,
  voter_fingerprint text not null,
  created_at timestamptz not null default now(),
  unique (report_id, voter_fingerprint)
);

create table if not exists public.ward_escalations (
  id uuid primary key default gen_random_uuid(),
  ward_number integer not null references public.wards(ward_number),
  threshold integer not null,
  report_count integer not null,
  escalation_type text not null default 'whatsapp',
  created_at timestamptz not null default now(),
  unique (ward_number, threshold)
);

create index if not exists garbage_reports_ward_idx on public.garbage_reports (ward_number);
create index if not exists garbage_reports_status_idx on public.garbage_reports (status);
create index if not exists garbage_reports_moderation_idx on public.garbage_reports (moderation_status);
create index if not exists representatives_role_constituency_idx on public.representatives (role, constituency);

