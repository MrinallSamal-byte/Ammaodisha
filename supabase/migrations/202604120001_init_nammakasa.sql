create or replace function public.ward_geom(geo jsonb)
returns geometry language sql immutable as $$
  select st_setsrid(st_geomfromgeojson((geo->'geometry')::text), 4326);
$$;

create or replace function public.find_ward_by_location(p_lat numeric, p_lng numeric)
returns table (
  ward_number integer,
  ward_name text,
  zone text,
  assembly_constituency text,
  parliamentary_constituency text,
  center_lat numeric,
  center_lng numeric
)
language sql stable as $$
  select w.ward_number, w.ward_name, w.zone, w.assembly_constituency, w.parliamentary_constituency, w.center_lat, w.center_lng
  from public.wards w
  where w.boundary_geojson is not null
    and st_contains(public.ward_geom(w.boundary_geojson), st_setsrid(st_makepoint(p_lng::float8, p_lat::float8), 4326))
  limit 1;
$$;

create or replace function public.find_nearest_ward(p_lat numeric, p_lng numeric)
returns table (
  ward_number integer,
  ward_name text,
  zone text,
  assembly_constituency text,
  parliamentary_constituency text,
  center_lat numeric,
  center_lng numeric
)
language sql stable as $$
  select w.ward_number, w.ward_name, w.zone, w.assembly_constituency, w.parliamentary_constituency, w.center_lat, w.center_lng
  from public.wards w
  order by st_distance(
    st_setsrid(st_makepoint(w.center_lng::float8, w.center_lat::float8), 4326)::geography,
    st_setsrid(st_makepoint(p_lng::float8, p_lat::float8), 4326)::geography
  )
  limit 1;
$$;

create or replace function public.get_all_ward_boundaries()
returns jsonb language sql stable as $$
  select jsonb_build_object(
    'type', 'FeatureCollection',
    'features', coalesce(jsonb_agg(boundary_geojson order by ward_number), '[]'::jsonb)
  )
  from public.wards
  where boundary_geojson is not null;
$$;

